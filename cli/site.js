// Operations on a site directory: scaffold it from the template, install or
// remove registry packages, and regenerate apps/installed.js.

import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { packageRoot } from "./registry.js";

export const templateDir = () => path.join(packageRoot(), "template");

const exists = async (target) => {
  try {
    await stat(target);
    return true;
  } catch {
    return false;
  }
};

const isSiteDir = async (dir) => exists(path.join(dir, "kit", "boot.js"));

export const assertSiteDir = async (dir) => {
  if (!(await isSiteDir(dir))) {
    throw new Error(`${dir} is not a win98-site-kit site (kit/boot.js not found). Run "init" first.`);
  }
};

/** Copies the template into `dir`, which must not already contain a site. */
export const initSite = async (dir, { force = false } = {}) => {
  const target = path.resolve(dir);
  if ((await exists(target)) && !force) {
    const entries = await readdir(target);
    if (entries.filter((name) => name !== ".git" && name !== ".DS_Store").length) {
      throw new Error(`${target} is not empty. Choose an empty directory or pass --force.`);
    }
  }
  await mkdir(target, { recursive: true });
  await cp(templateDir(), target, { recursive: true, force: true });
  return target;
};

const camelCase = (id) => id.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());

/** Rewrites apps/installed.js from the app folders found under apps/. */
export const syncInstalled = async (dir) => {
  await assertSiteDir(dir);
  const appsDir = path.join(dir, "apps");
  const entries = (await readdir(appsDir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const ids = [];
  for (const id of entries) {
    if (await exists(path.join(appsDir, id, "index.js"))) ids.push(id);
  }
  const imports = ids.map((id) => `import ${camelCase(id)} from "./${id}/index.js";`).join("\n");
  const list = ids.map(camelCase).join(", ");
  const content = `// GENERATED by \`win98-site-kit sync\` from the folders under apps/.
// Each folder's index.js default-exports an app definition (see kit/apps.js).
// Re-run \`npx win98-site-kit sync\` after adding or removing an app folder,
// or edit this list by hand; order here is the fallback desktop/dock order.

${imports}

export default [${list}];
`;
  await writeFile(path.join(appsDir, "installed.js"), content);
  return ids;
};

/** Reads the manifest the CLI stored when it installed `id`, if any. */
const installedManifest = async (dir, id) => {
  const file = path.join(dir, "apps", id, "manifest.json");
  if (!(await exists(file))) return null;
  return JSON.parse(await readFile(file, "utf8"));
};

/**
 * Installs a registry package into the site. Existing files are never
 * overwritten unless `force` is set; dependencies listed in `requires` are
 * installed first. Returns the list of written paths.
 */
export const addPackage = async (dir, registry, id, { force = false, log = () => {} } = {}) => {
  await assertSiteDir(dir);
  const manifest = await registry.manifest(id);
  const written = [];
  for (const dependency of manifest.requires ?? []) {
    if (await exists(path.join(dir, "apps", dependency, "index.js"))) continue;
    log(`Installing ${dependency} (required by ${id})`);
    written.push(...(await addPackage(dir, registry, dependency, { force, log })));
  }
  const conflicts = [];
  for (const relativePath of manifest.files) {
    if (!force && (await exists(path.join(dir, relativePath)))) conflicts.push(relativePath);
  }
  if (conflicts.length) {
    throw new Error(
      `${id} would overwrite existing files (pass --force to replace them):\n  ${conflicts.join("\n  ")}`
    );
  }
  for (const relativePath of manifest.files) {
    const bytes = await registry.file(id, relativePath);
    const target = path.join(dir, relativePath);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, bytes);
    written.push(relativePath);
  }
  const manifestTarget = path.join(dir, "apps", id, "manifest.json");
  await writeFile(manifestTarget, `${JSON.stringify(manifest, null, 2)}\n`);
  written.push(`apps/${id}/manifest.json`);
  await syncInstalled(dir);
  return written;
};

/** Removes an installed package's files (from its stored manifest) and resyncs. */
export const removePackage = async (dir, id) => {
  await assertSiteDir(dir);
  const manifest = await installedManifest(dir, id);
  const appDir = path.join(dir, "apps", id);
  if (!manifest && !(await exists(appDir))) throw new Error(`${id} is not installed`);
  const removed = [];
  for (const relativePath of manifest?.files ?? []) {
    const target = path.join(dir, relativePath);
    if (await exists(target)) {
      await rm(target);
      removed.push(relativePath);
    }
  }
  await rm(appDir, { recursive: true, force: true });
  // Drop asset folders the package owned once they are empty.
  const dirs = new Set((manifest?.files ?? []).map((file) => path.dirname(file)));
  for (const relativeDir of [...dirs].sort((a, b) => b.length - a.length)) {
    const target = path.join(dir, relativeDir);
    if ((await exists(target)) && (await readdir(target)).length === 0) await rm(target, { recursive: true });
  }
  await syncInstalled(dir);
  return removed;
};

/** Ids of installed apps (folders under apps/ with an index.js). */
export const installedIds = async (dir) => {
  await assertSiteDir(dir);
  const appsDir = path.join(dir, "apps");
  const ids = [];
  for (const entry of await readdir(appsDir, { withFileTypes: true })) {
    if (entry.isDirectory() && (await exists(path.join(appsDir, entry.name, "index.js")))) ids.push(entry.name);
  }
  return ids.sort();
};
